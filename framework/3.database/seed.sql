-- ------------------------------------------------------------
-- 导入后必跑：名额一致性校验（每个室都应显示 OK）
-- ------------------------------------------------------------
SELECT l.code,
       l.name,
       l.quota              AS 室总名额,
       SUM(m.quota)         AS 导师名额合计,
       COUNT(m.id)          AS 导师数,
       CASE WHEN l.quota = SUM(m.quota) THEN 'OK' ELSE '不一致' END AS 结果
  FROM lab l
  LEFT JOIN mentor m ON m.lab_id = l.id
 GROUP BY l.id
 ORDER BY l.code;
